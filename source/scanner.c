static void append_log(const char *fmt, ...)
{
    char line[768];
    va_list args;
    int fd;
    int len;

    ensure_output_dir();

    va_start(args, fmt);
    len = vsnprintf(line, sizeof(line), fmt, args);
    va_end(args);

    if (len < 0)
        return;

    if ((size_t)len >= sizeof(line))
        len = sizeof(line) - 1;

    fd = open(DIAG_LOG, O_WRONLY | O_CREAT | O_APPEND, 0666);
    if (fd < 0)
        return;

    write(fd, line, (size_t)len);
    write(fd, "\n", 1);
    close(fd);
}

static void notify_status(const char *fmt, ...)
{
    char message[512];
    va_list args;

    va_start(args, fmt);
    vsnprintf(message, sizeof(message), fmt, args);
    va_end(args);

    NotifyStatic(TEX_ICON_SYSTEM, message);
    append_log("%s", message);
}

static int read_process(uint64_t address, void *data, size_t length)
{
    struct proc_rw rw;
    memset(&rw, 0, sizeof(rw));
    rw.address = address;
    rw.data = data;
    rw.length = length;
    rw.write_flags = 0;
    return sys_sdk_proc_rw(&rw);
}

static int write_process(uint64_t address, const void *data, size_t length)
{
    struct proc_rw rw;
    memset(&rw, 0, sizeof(rw));
    rw.address = address;
    rw.data = (void *)data;
    rw.length = length;
    rw.write_flags = 1;
    return sys_sdk_proc_rw(&rw);
}

static void load_master_candidates(void)
{
    const uint64_t region_start = 0x0000000FE032CC00ULL;
    const uint64_t region_end   = 0x0000000FE032D400ULL;

    g_candidate_count = 0;
    g_measurement_index = 1;
    g_mode = SCAN_MODE_INT32;

    size_t invalid = 0;
    size_t out_of_range = 0;
    size_t read_fail = 0;

    for (uint64_t address = region_start;
         address + sizeof(uint32_t) <= region_end;
         address += sizeof(uint32_t)) {
        OrbisKernelVirtualQueryInfo info;
        uint32_t raw = 0;
        int32_t value = 0;

        if (sceKernelVirtualQuery((void *)(uintptr_t)address, 0,
                                  &info, sizeof(info)) < 0 ||
            (info.prot & CPU_READ) == 0 ||
            (info.prot & CPU_WRITE) == 0) {
            invalid++;
            continue;
        }

        if (read_process(address, &raw, sizeof(raw)) != 0) {
            read_fail++;
            continue;
        }

        memcpy(&value, &raw, sizeof(value));
        if (value < 0 || value > 255) {
            out_of_range++;
            continue;
        }

        if (g_candidate_count >= MAX_CANDIDATES)
            break;

        g_candidate_address[g_candidate_count] = address;
        g_candidate_previous[g_candidate_count] = raw;
        g_candidate_count++;
    }

    dump_candidates();
    append_log("=== CareerDiag STARREG v1060 live load ===");
    append_log("region=0x%llX..0x%llX aligned_int32=%zu valid=%zu invalid=%zu out_of_range=%zu read_fail=%zu",
               (unsigned long long)region_start,
               (unsigned long long)region_end,
               (size_t)((region_end - region_start) / 4),
               g_candidate_count, invalid, out_of_range, read_fail);

    notify_status("[CareerDiag STARREG v1060] %zu candidatos na regiao da estrela. R2+ESQ testa 10.",
                  g_candidate_count);
}

static bool load_single_candidate_from_file(void)
{
    int fd;
    char buf[1024];
    ssize_t n;
    char *p;
    unsigned long long address = 0;
    int value = 0;
    uint32_t raw = 0;
    int32_t current = 0;
    OrbisKernelVirtualQueryInfo info;

    ensure_output_dir();
    fd = open(DIAG_RESULTS, O_RDONLY, 0);
    if (fd < 0)
        return false;

    n = read(fd, buf, sizeof(buf) - 1);
    close(fd);
    if (n <= 0)
        return false;

    buf[n] = '\0';
    if (strstr(buf, "candidates=1") == NULL)
        return false;

    p = strstr(buf, "0x");
    if (p == NULL || sscanf(p, "0x%llX  int32=%d", &address, &value) != 2)
        return false;

    if (sceKernelVirtualQuery((void *)(uintptr_t)address, 0, &info, sizeof(info)) < 0 ||
        (info.prot & CPU_READ) == 0 || (info.prot & CPU_WRITE) == 0)
        return false;

    if (read_process((uint64_t)address, &raw, sizeof(raw)) != 0)
        return false;

    memcpy(&current, &raw, sizeof(current));
    if (current < 0 || current > 255)
        return false;

    g_candidate_address[0] = (uint64_t)address;
    g_candidate_previous[0] = raw;
    g_candidate_count = 1;

    notify_status("[CareerDiag] Alvo restaurado 0x%llX valor=%d. R1+CIMA/BAIXO ajusta.",
                  address, current);
    return true;
}

static void adjust_single_candidate(int delta)
{
    uint64_t address;
    uint32_t raw = 0;
    int32_t value = 0;
    int32_t next;
    OrbisKernelVirtualQueryInfo info;

    if (g_candidate_count != 1) {
        notify_status("[CareerDiag] Ainda ha %zu candidatos; continue filtrando.", g_candidate_count);
        return;
    }

    address = g_candidate_address[0];

    if (sceKernelVirtualQuery((void *)(uintptr_t)address, 0, &info, sizeof(info)) < 0 ||
        (info.prot & CPU_READ) == 0 || (info.prot & CPU_WRITE) == 0) {
        notify_status("[CareerDiag] Alvo nao esta gravavel; refaca a busca.");
        return;
    }

    if (read_process(address, &raw, sizeof(raw)) != 0) {
        notify_status("[CareerDiag] Falha ao ler o alvo.");
        return;
    }

    memcpy(&value, &raw, sizeof(value));
    if (value < 0 || value > 255) {
        notify_status("[CareerDiag] Valor atual %d fora de 0..255; nao alterado.", value);
        return;
    }

    next = value + delta;
    if (next < 0) next = 0;
    if (next > 255) next = 255;

    if (write_process(address, &next, sizeof(next)) != 0) {
        notify_status("[CareerDiag] Falha ao escrever no alvo.");
        return;
    }

    memcpy(&g_candidate_previous[0], &next, sizeof(next));
    dump_candidates();

    notify_status("[CareerDiag] REP 0x%llX: %d -> %d (%+d).",
                  (unsigned long long)address, value, next, delta);
}

static void enforce_freeze_max(void)
{
    uint64_t address;
    int32_t target = 255;
    uint32_t raw = 0;
    int32_t current = 0;
    OrbisKernelVirtualQueryInfo info;

    if (!g_freeze_max || g_candidate_count != 1)
        return;

    address = g_candidate_address[0];

    if (sceKernelVirtualQuery((void *)(uintptr_t)address, 0, &info, sizeof(info)) < 0 ||
        (info.prot & CPU_READ) == 0 || (info.prot & CPU_WRITE) == 0) {
        g_freeze_max = 0;
        notify_status("[CareerDiag] FREEZE OFF: alvo invalido/nao gravavel.");
        return;
    }

    if (read_process(address, &raw, sizeof(raw)) != 0) {
        g_freeze_max = 0;
        notify_status("[CareerDiag] FREEZE OFF: falha ao ler alvo.");
        return;
    }

    memcpy(&current, &raw, sizeof(current));

    if (current < 0 || current > 255) {
        g_freeze_max = 0;
        notify_status("[CareerDiag] FREEZE OFF: valor %d fora de 0..255.", current);
        return;
    }

    if (current != target) {
        if (write_process(address, &target, sizeof(target)) != 0) {
            g_freeze_max = 0;
            notify_status("[CareerDiag] FREEZE OFF: falha ao escrever 255.");
            return;
        }

        memcpy(&g_candidate_previous[0], &target, sizeof(target));
        append_log("[CareerDiag] FREEZE regravou 0x%llX: %d -> 255",
                   (unsigned long long)address, current);
    }
}

static void toggle_freeze_max(void)
{
    if (g_candidate_count != 1) {
        notify_status("[CareerDiag] FREEZE requer 1 candidato; atual=%zu.", g_candidate_count);
        return;
    }

    g_freeze_max = !g_freeze_max;

    if (g_freeze_max) {
        enforce_freeze_max();
        if (g_freeze_max)
            notify_status("[CareerDiag] FREEZE MAX ON: alvo preso em 255.");
    } else {
        notify_status("[CareerDiag] FREEZE MAX OFF.");
    }
}

